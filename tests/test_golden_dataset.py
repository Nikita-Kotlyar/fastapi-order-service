from __future__ import annotations

import csv
from datetime import date

import pytest
from sqlalchemy import func, select

from app.ingestion.master_data import seed_master_data
from app.models import Issue, Order, OrderLink
from app.services.reconciliation import ReconciliationService

pytestmark = pytest.mark.integration

SOURCE_COLUMNS = {
    "source_1c": "1c_orders",
    "source_crm": "crm_deals",
    "source_email": "email_orders",
    "source_production": "production_orders",
    "source_warehouse": "warehouse_requests",
}

# Counts that the curated expected file contains. Some expected rows are
# over-generated by the reference generator's block-based index formula; the service
# detects the defect that actually exists in the data, so for a few types the
# real count is lower than the curated file. See README "Профили сверки".
EXPECTED_MINIMUM = {
    "duplicate_1c": 50,
    "unit_mismatch": 150,
    "total_mismatch": 60,
    "unknown_sku": 40,
    "missing_customer": 30,
    "mixed_unit": 20,
    "missing_conversion": 20,
    "duplicate_crm": 30,
    "duplicate_warehouse": 10,
    "orphan_production": 50,
    "email_only": 50,
    "contradictory_conversion": 100,
}


@pytest.fixture()
def reconciled(db, full_dataset):
    seed_master_data(db, full_dataset)
    db.commit()
    service = ReconciliationService(db)
    result = service.run(full_dataset, profile="full", run_date=date(2026, 11, 5))
    return db, result


def test_canonical_order_count_and_source_coverage(reconciled) -> None:
    db, result = reconciled
    stats = result["stats"]
    assert stats["orders"] == 580
    assert stats["by_source"] == {
        "1c_orders": 400,
        "crm_deals": 309,
        "email_orders": 183,
        "production_orders": 250,
        "warehouse_requests": 200,
    }
    assert db.scalar(select(func.count()).select_from(Order)) == 580


def test_canonical_order_ids_match_reference(reconciled, full_dataset) -> None:
    db, _result = reconciled
    with open(
        full_dataset / "expected/11_канонические_заказы.csv", encoding="utf-8-sig", newline=""
    ) as handle:
        expected = list(csv.DictReader(handle, delimiter=";"))

    actual: dict[str, set[tuple[str, str]]] = {}
    for order in db.scalars(select(Order)):
        actual[order.canonical_order_id] = {
            (link.source_type, link.source_id)
            for link in db.scalars(select(OrderLink).where(OrderLink.order_id == order.id))
        }

    exact = 0
    mismatches: list[str] = []
    for row in expected:
        expected_links = {
            (source_type, row[column]) for column, source_type in SOURCE_COLUMNS.items() if row[column]
        }
        if actual.get(row["canonical_order_id"]) == expected_links:
            exact += 1
        else:
            mismatches.append(row["canonical_order_id"])

    # One customer+date pair is genuinely ambiguous: two orders have the same
    # customer and date, and the email has no SKU overlap with either.
    assert exact >= 578, mismatches
    ambiguous = db.scalar(
        select(func.count()).select_from(Issue).where(Issue.issue_type == "ambiguous_match")
    )
    assert ambiguous and ambiguous >= 1


def test_issue_detectors_meet_reference_baseline(reconciled) -> None:
    db, _result = reconciled
    counts = {
        issue_type: count
        for issue_type, count in db.execute(select(Issue.issue_type, func.count()).group_by(Issue.issue_type))
    }
    for issue_type, minimum in EXPECTED_MINIMUM.items():
        assert counts.get(issue_type, 0) >= minimum, (issue_type, counts.get(issue_type, 0), minimum)

    # These two counts are lower than the curated file because the file contains
    # 21 mixed-unit rows that cannot be negative and 4 status rows without a real
    # CRM conflict. The service reports only defects that exist in the data.
    assert counts["status_conflict"] == 46
    assert counts["negative_qty"] == 29

    assert counts["coverage_gap"] == 1
    assert counts["orphan_warehouse"] >= 10


def test_reference_profile_excludes_extended_signals(db, full_dataset) -> None:
    seed_master_data(db, full_dataset)
    db.commit()
    result = ReconciliationService(db).run(full_dataset, profile="reference", run_date=date(2026, 11, 5))
    types = {issue.issue_type for issue in db.scalars(select(Issue))}
    assert result["stats"]["orders"] == 580
    assert "coverage_gap" not in types
    assert "orphan_warehouse" not in types
    assert "ambiguous_date" not in types
    assert "ambiguous_match" not in types
